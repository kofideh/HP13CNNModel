def main() -> None:
    args = parse_args()

    weights_path = os.path.join(args.output_dir, args.weights_dir, "trained_hybrid_positive.pth")
    training_data_info_path = os.path.join(args.output_dir, args.weights_dir, "training_report.md")
    if not os.path.exists(weights_path):
        raise FileNotFoundError(f"Model weights file not found: {weights_path}")
    if not os.path.exists(training_data_info_path):
        raise FileNotFoundError(f"Training report not found: {training_data_info_path}")

    cfg = load_training_config(training_data_info_path)
    cfg["SNR_MIN"] = float(args.snr_min if args.snr_min is not None else cfg["SNR_MIN"])
    cfg["SNR_MAX"] = float(args.snr_max if args.snr_max is not None else cfg["SNR_MAX"])

    n_timepoints = int(cfg["NUM_TIMEPOINTS"])
    time_points = np.arange(0, n_timepoints * float(cfg["SCAN_TR"]), float(cfg["SCAN_TR"]))
    generator, aif_key = build_generator(cfg, time_points)

    timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    run_dir = os.path.join(args.output_dir, args.weights_dir, f"simulatedData_equalNoise_gammaAIF_{timestamp}")
    os.makedirs(run_dir, exist_ok=True)

    # 1. Generate clean curves, then add equal-rms noise explicitly.
    X_clean, y, met_pools, _ = generate_clean_dataset(generator, n_samples=args.n_samples)
    rng = np.random.default_rng(args.noise_seed)
    X, noise_df = add_equal_rms_noise(
        X_clean=X_clean,
        rng=rng,
        target_pyr_snr_range=(cfg["SNR_MIN"], cfg["SNR_MAX"]),
        fixed_pyr_snr=args.fixed_pyr_snr,
        clip_negative=args.clip_negative_noisy_signal,
    )
    noise_df.to_csv(os.path.join(run_dir, "per_sample_equal_rms_noise_and_snr.csv"), index=False)

    snr_pyr_report = float(noise_df["snr_pyr"].mean())
    snr_lac_report = float(noise_df["snr_lac"].mean())
    snr_label = f"SNR_Pyr_{snr_pyr_report:.1f}_SNR_Lac_{snr_lac_report:.1f}".replace(".", "p")

    # 2. Prepare network inputs exactly as in the training/inference pipeline.
    Xn_test, Xr_test, X_norm, X_raw, clin_meta, alpha, P_clin = prepare_inputs_for_model(
        X, cfg=cfg, P_train=cfg["P_TRAIN"]
    )
    Xr_test_tensor = torch.tensor(Xr_test, dtype=torch.float32)
    Xn_test_tensor = torch.tensor(Xn_test, dtype=torch.float32)
    y_true = np.asarray(y, dtype=float)

    # 3. Load model and infer.
    model = HybridMultiHead(
        input_dim_raw=n_timepoints * 2,
        input_dim_norm=n_timepoints * 2,
        vb_range=(cfg["VB_MIN"], cfg["VB_MAX"]),
        kpl_range=(cfg["KPL_MIN"], cfg["KPL_MAX"]),
        kve_range=(cfg["KVE_MIN"], cfg["KVE_MAX"]),
    )
    model.load_state_dict(torch.load(weights_path, map_location=torch.device("cpu")))
    model.eval()
    with torch.no_grad():
        y_pred_nn = model(Xn_test_tensor, Xr_test_tensor).cpu().numpy()

    # 4. NLLS comparison, using same noisy data and optionally same known sigma for both channels.
    print("Using gamma-AIF NLLS fitting...")
    y_pred_nlls, nlls_results, nlls_failures, nlls_elapsed = run_nlls_fits(
        X=X,
        y_true=y_true,
        noise_df=noise_df,
        cfg=cfg,
        time_points=time_points,
        weighted=args.use_weighted_nlls,
        aif_key=aif_key,
    )
    print(f"NLLS fitting time: {nlls_elapsed:.2f} seconds")
    print(f"NLLS failed or non-converged fits: {nlls_failures} / {X.shape[0]}")

    # 5. Save agreement CSVs and figures.
    nn_base = f"TrueVPred_{snr_label}_NeuralNetwork"
    nlls_base = f"TrueVPred_{snr_label}_NLLS"
    nn_csv = save_true_vs_pred_csv_and_quickplot(y_true, y_pred_nn, run_dir, nn_base)
    nlls_csv = save_true_vs_pred_csv_and_quickplot(y_true, y_pred_nlls, run_dir, nlls_base)

    plot_prediction_scatter(
        y_true,
        y_pred_nn,
        saveName=os.path.join(run_dir, f"NeuralNetwork_{snr_label}"),
    )
    plot_prediction_scatter(
        y_true,
        y_pred_nlls,
        saveName=os.path.join(run_dir, f"GammaAIF_NLLSFitOfGeneratorData_{snr_label}"),
    )

    agreement_script = os.path.join(os.path.dirname(os.path.abspath(__file__)), "plot_param_agreement.py")
    if not os.path.exists(agreement_script):
        agreement_script = "plot_param_agreement.py"
    cmd = [
        sys.executable,
        agreement_script,
        "--csv_nlls",
        nlls_csv,
        "--csv_nn",
        nn_csv,
        "--out",
        os.path.join(run_dir, f"TrueVPred_{snr_label}_Param_Agreement.png"),
        "--bootstrap",
        str(args.bootstrap),
    ]
    print("Running:", " ".join(cmd))
    subprocess.run(cmd, check=True)

    timecourse_path = plot_example_timecourses(
        X=X,
        y_true=y_true,
        y_pred_nn=y_pred_nn,
        y_pred_nlls=y_pred_nlls,
        nlls_results=nlls_results,
        noise_df=noise_df,
        cfg=cfg,
        generator=generator,
        aif_key=aif_key,
        time_points=time_points,
        run_dir=run_dir,
        snr_label=snr_label,
        n_examples=args.n_examples,
    )

    # 6. Summaries for manuscript/reporting.
    r2_nn = finite_r2(y_true, y_pred_nn)
    r2_nlls = finite_r2(y_true, y_pred_nlls)
    r2_nn_std = bootstrap_r2_std(y_true, y_pred_nn, args.bootstrap, rng)
    r2_nlls_std = bootstrap_r2_std(y_true, y_pred_nlls, args.bootstrap, rng)

    summary_df = pd.DataFrame(
        {
            "SNR_Pyruvate_mean": [snr_pyr_report],
            "SNR_Lactate_mean": [snr_lac_report],
            "SNR_Pyruvate_median": [float(noise_df["snr_pyr"].median())],
            "SNR_Lactate_median": [float(noise_df["snr_lac"].median())],
            "sigma_equal_rms_mean": [float(noise_df["sigma_equal_rms"].mean())],
            "R2_NN_kPL": [r2_nn[0]],
            "R2_NN_kPL_std": [r2_nn_std[0]],
            "R2_NN_kVE": [r2_nn[1]],
            "R2_NN_kVE_std": [r2_nn_std[1]],
            "R2_NN_vB": [r2_nn[2]],
            "R2_NN_vB_std": [r2_nn_std[2]],
            "R2_NLLS_kPL": [r2_nlls[0]],
            "R2_NLLS_kPL_std": [r2_nlls_std[0]],
            "R2_NLLS_kVE": [r2_nlls[1]],
            "R2_NLLS_kVE_std": [r2_nlls_std[1]],
            "R2_NLLS_vB": [r2_nlls[2]],
            "R2_NLLS_vB_std": [r2_nlls_std[2]],
            "n_samples": [X.shape[0]],
            "nlls_failures": [nlls_failures],
            "weighted_nlls": [bool(args.use_weighted_nlls)],
            "alpha_input_alignment": [alpha],
            "P_clin": [P_clin],
            "P_train": [cfg["P_TRAIN"]],
        }
    )
    summary_xlsx = os.path.join(run_dir, f"R2_SNR_Summary_{timestamp}.xlsx")
    with pd.ExcelWriter(summary_xlsx) as writer:
        summary_df.to_excel(writer, sheet_name="summary", index=False)
        noise_df.to_excel(writer, sheet_name="per_sample_noise", index=False)

    with open(os.path.join(run_dir, "summary_report.md"), "w", encoding="utf-8") as f:
        f.write("# HP-13C equal-rms noise simulation summary\n\n")
        f.write(f"Date: {datetime.now():%Y-%m-%d %H:%M:%S}\n\n")
        f.write(f"Samples: {X.shape[0]}\n\n")
        f.write("## Noise/SNR definition\n")
        f.write(
            "For each simulated voxel, the same Gaussian rms noise amplitude sigma was added "
            "independently to pyruvate and lactate. SNR was then computed from clean peak signal "
            "divided by that same sigma. Thus pyruvate and lactate SNR differ only because their "
            "signal peaks differ, not because different noise amplitudes were used.\n\n"
        )
        f.write(
            "NLLS used the gamma-variate vascular-input model, fitting AIF nuisance parameters "
            "jointly with kPL, kVE, and vB. NN forward curves in the time-course figure were "
            "generated only for visualization by fitting the gamma-AIF nuisance parameters with "
            "the NN kinetic estimates held fixed.\n\n"
        )
        f.write(f"Mean pyruvate/lactate SNR: {snr_pyr_report:.2f}/{snr_lac_report:.2f}\n")
        f.write(
            f"Median pyruvate/lactate SNR: {noise_df['snr_pyr'].median():.2f}/"
            f"{noise_df['snr_lac'].median():.2f}\n\n"
        )
        f.write("## R2 values\n")
        for i, name in enumerate(PARAMETER_NAMES):
            f.write(
                f"- {name}: NN R2={r2_nn[i]:.3f} ± {r2_nn_std[i]:.3f}; "
                f"NLLS R2={r2_nlls[i]:.3f} ± {r2_nlls_std[i]:.3f}\n"
            )
        f.write("\n## Output files\n")
        f.write(f"- NN CSV: {os.path.basename(nn_csv)}\n")
        f.write(f"- NLLS CSV: {os.path.basename(nlls_csv)}\n")
        f.write(f"- Example timecourses: {os.path.basename(timecourse_path)}\n")
        f.write(f"- Summary workbook: {os.path.basename(summary_xlsx)}\n")

    print("\n" + "=" * 80)
    print("EQUAL-RMS NOISE SIMULATION COMPLETE")
    print("=" * 80)
    print(f"Output directory: {run_dir}")
    print(f"Mean SNR Pyr/Lac: {snr_pyr_report:.2f}/{snr_lac_report:.2f}")
    print(f"Example timecourses: {timecourse_path}")
    print(f"Summary workbook: {summary_xlsx}")
    print("=" * 80)


if __name__ == "__main__":
    main()
