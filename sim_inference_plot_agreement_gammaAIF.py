def _as_schedule(x: Sequence[float] | float, n: int) -> np.ndarray:
    arr = np.asarray(x, dtype=float)
    if arr.ndim == 0:
        return np.repeat(float(arr), n)
    if arr.size == n:
        return arr.astype(float)
    if arr.size > n:
        return arr[:n].astype(float)
    return np.pad(arr.astype(float), (0, n - arr.size), mode="edge")


def r1_app_schedule(R1: float, flip_angle_deg: Sequence[float] | float, TR: float, n: int) -> np.ndarray:
    """Return R1,app(t) = R1 - log(cos(theta(t))) / TR for each acquired time point."""
    fa = _as_schedule(flip_angle_deg, n)
    c = np.cos(np.deg2rad(fa))
    c = np.clip(c, 1e-8, 1.0)
    return float(R1) - np.log(c) / float(TR)



